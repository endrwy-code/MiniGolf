#!/usr/bin/env python3
"""Inject the floor-plan data into the status page, so its map is drawn from the repo's files.

Usage:
    python3 tools/make_status_page.py [LAYOUT_JSON] [DIMENSIONS_JSON] [--page status/countdown-golf-status.html] [--check]

    LAYOUT_JSON      default floorplan/layout-v3-nyc.json (written by tools/make_layout_nyc.py)
    DIMENSIONS_JSON  default floorplan/auditorium-dimensions.json (room geometry, every value
                     labelled measured, derived or not measured)

Writes one JSON block into the page between the /* STATUS:BEGIN */ and /* STATUS:END */ markers;
the page's own script draws the map, the hole cards and the clearance list from it. Edit this
script or the source files, never the block. --check builds the block and prints a summary
without writing the page. Re-run it whenever the layout or the geometry changes.

Nothing about a particular layout version is assumed. The room length, the hole list and every
hole field come from the files; the script stops with a message naming the field if one it needs
is missing. Needed: auditorium.length_x and width_z, stage.front_x, runway.x and z, golf_limit.x
and from_stage_front; for each hole n, d, name, L, W, c and th. Everything else is optional and
passed through (sign, cls, par, glow, surface, play, prop, clock, a district name, footprints,
hub or hubs, routes, sightline, checks_m).

Cables: `cables` in the geometry file is either a string (not placed on this geometry yet) or an
object {"_about", "confidence", "runs": [{"id", "label", "kind": "run"|"trunk"|"drop",
"points": [[x, z], ...]}], "power_flags": [{"node", "circuit", "load_percent", "x", "z"}]}.
For an object the page draws the runs as dashed lines labelled approximate and marks the power
flags; for a string it shows a short note that the cables aren't placed yet. Anything else fails.

Standard library only.
"""
import argparse
import json
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_LAYOUT = os.path.join(ROOT, "floorplan", "layout-v3-nyc.json")
DEFAULT_DIMS = os.path.join(ROOT, "floorplan", "auditorium-dimensions.json")
DEFAULT_PAGE = os.path.join(ROOT, "status", "countdown-golf-status.html")
# District names from docs/10-new-york-concept.md, used only when a hole carries no "district" field.
DISTRICT_NAMES = {"A": "Downtown", "B": "Midtown"}
CABLE_KINDS = ("run", "trunk", "drop")
HOLE_NEEDS = ("n", "d", "name", "L", "W", "c", "th")
BEGIN = "/* STATUS:BEGIN (generated by tools/make_status_page.py; edit the script, not this block) */"
END = "/* STATUS:END */"


def fail(msg):
    sys.exit(f"make_status_page: {msg}")


def need(obj, path, src):
    """Follow a dotted path; stop with a clear message if any step is missing."""
    cur = obj
    for step in path.split("."):
        if not isinstance(cur, dict) or step not in cur:
            fail(f"{src}: needs '{path}', but it is missing")
        cur = cur[step]
    return cur


def measured(conf):
    """True when the geometry file says a value was measured, or derived from measured values."""
    c = (conf or "").strip().lower()
    return c.startswith("measured") or c.startswith("derived")


def r3(v):
    return round(float(v), 3)


def pair(v, what):
    if not (isinstance(v, (list, tuple)) and len(v) == 2 and all(isinstance(a, (int, float)) for a in v)):
        fail(f"{what} must be a pair of numbers, got {v!r}")
    return [r3(v[0]), r3(v[1])]


def pts(seq, what="points"):
    return [pair(q, what) for q in seq]


def l2w(h, u, v):
    t = math.radians(h["th"])
    return (h["c"][0] + u * math.cos(t) - v * math.sin(t), h["c"][1] + u * math.sin(t) + v * math.cos(t))


# ---------------------------------------------------------------- geometry
def geometry(dims, src):
    L = need(dims, "auditorium.length_x", src)
    W = need(dims, "auditorium.width_z", src)
    SF = need(dims, "stage.front_x", src)
    rwx = pair(need(dims, "runway.x", src), "runway.x")
    rwz = pair(need(dims, "runway.z", src), "runway.z")
    gx = need(dims, "golf_limit.x", src)
    gfrom = need(dims, "golf_limit.from_stage_front", src)
    room, rw, gl = dims["auditorium"], dims["runway"], dims["golf_limit"]
    out = {
        "version": dims.get("version"),
        "date": dims.get("date"),
        "room": {"L": L, "W": W,
                 "L_measured": measured(room.get("length_confidence")),
                 "W_measured": measured(room.get("width_confidence"))},
        "stage": {"front_x": SF, "measured": measured(dims["stage"].get("front_x_confidence")), "curves": []},
        "runway": {"x": rwx, "z": rwz, "length": rw.get("length", r3(rwx[1] - rwx[0])),
                   "width": rw.get("width", r3(rwz[1] - rwz[0])), "height": rw.get("height"),
                   "measured": measured(rw.get("length_confidence")) and measured(rw.get("width_confidence", "measured"))},
        "golf_limit": {"x": gx, "from_stage_front": gfrom, "past_tip": gl.get("past_runway_tip"),
                       "measured": measured(gl.get("from_stage_front_confidence"))},
        "zones": [],
        "side_items": [],
        "doors": [],
        "extras": [],
    }
    for i, c in enumerate(dims["stage"].get("corner_curves", [])):
        for k in ("wall_z", "along_front", "out_from_front"):
            if k not in c:
                fail(f"{src}: stage.corner_curves[{i}] needs '{k}'")
        out["stage"]["curves"].append({"wall_z": c["wall_z"], "along": c["along_front"], "out": c["out_from_front"],
                                       "measured": measured(c.get("confidence"))})
    for i, z in enumerate(dims.get("zones", [])):
        if "x" not in z or "z" not in z:
            fail(f"{src}: zones[{i}] needs 'x' and 'z'")
        out["zones"].append({"id": z.get("id", f"zone{i}"), "label": z.get("label", ""),
                             "x": pair(z["x"], f"zones[{i}].x"), "z": pair(z["z"], f"zones[{i}].z")})
    sides = dims.get("runway_side_items", {})
    tip = rwx[1]
    for side in sides.get("sides", []):
        for i, it in enumerate(sides.get("items", [])):
            for k in ("type", "from_tip", "out"):
                if k not in it:
                    fail(f"{src}: runway_side_items.items[{i}] needs '{k}'")
            a, b = pair(it["from_tip"], f"runway_side_items.items[{i}].from_tip")
            o = it["out"]
            z = [rwz[0] - o, rwz[0]] if side == "top" else [rwz[1], rwz[1] + o]
            out["side_items"].append({"type": it["type"], "side": side, "x": [r3(tip - b), r3(tip - a)],
                                      "z": [r3(z[0]), r3(z[1])], "measured": measured(it.get("position_confidence"))})
    if "lf_platform" in dims:
        lf = dims["lf_platform"]
        out["lf_platform"] = {"label": lf.get("label", "LF platform"),
                              "x": pair(need(dims, "lf_platform.x", src), "lf_platform.x"),
                              "z": pair(need(dims, "lf_platform.z", src), "lf_platform.z"),
                              "measured": measured(lf.get("x_confidence")) and measured(lf.get("z_confidence"))}
    if "sound_console" in dims:
        sc = dims["sound_console"]
        out["console"] = {"x": pair(need(dims, "sound_console.x", src), "sound_console.x"),
                          "z": pair(need(dims, "sound_console.z", src), "sound_console.z"),
                          "measured": measured(sc.get("confidence"))}
    for i, d in enumerate(dims.get("doors", [])):
        wall = str(d.get("wall", "")).split(" ")[0].lower()
        if wall in ("back", "stage", "end"):
            if "z" not in d:
                fail(f"{src}: doors[{i}] is on the {wall} wall and needs 'z'")
            x = L if wall == "back" else 0.0
            seg = [[x, d["z"][0]], [x, d["z"][1]]]
        elif wall in ("top", "bottom"):
            if "x" not in d:
                fail(f"{src}: doors[{i}] is on the {wall} wall and needs 'x'")
            z = 0.0 if wall == "top" else W
            seg = [[d["x"][0], z], [d["x"][1], z]]
        else:
            fail(f"{src}: doors[{i}] has wall '{d.get('wall')}'; expected back, stage, top or bottom")
        out["doors"].append({"id": d.get("id", f"door{i}"), "wall": wall, "seg": pts(seg, f"doors[{i}]"),
                             "note": d.get("note", ""), "measured": measured(d.get("confidence"))})
    # Anything else with an x and z extent (top level, or inside photo_estimates), drawn as a dashed outline.
    handled = {"auditorium", "stage", "runway", "runway_side_items", "golf_limit", "zones", "lf_platform",
               "sound_console", "doors", "measurements", "not_measured", "cables", "coordinate_system"}
    pools = [(k, v) for k, v in dims.items() if k not in handled]
    pe = dims.get("photo_estimates")
    if isinstance(pe, dict):
        pools += [(k, v) for k, v in pe.items()]
    for k, v in pools:
        if not isinstance(v, dict):
            continue
        xr = v.get("x", v.get("x_used"))
        zr = v.get("z", v.get("z_used"))
        if not (isinstance(xr, list) and isinstance(zr, list) and len(xr) == 2 and len(zr) == 2):
            continue
        overhead = any(key in v for key in ("underside_y", "y", "height_above_floor"))
        out["extras"].append({"id": k, "label": v.get("label", k.replace("_", " ")), "x": pair(xr, k + ".x"),
                              "z": pair(zr, k + ".z"), "overhead": overhead,
                              "measured": measured(v.get("confidence"))})
    m = {}
    for k in dims.get("measurements", []):
        if "id" in k and "value" in k:
            m[k["id"]] = {"value": k["value"], "measured": measured(k.get("confidence"))}
    out["measurements"] = m
    out["not_measured"] = dims.get("not_measured", [])
    return out


def cables(dims, src):
    c = dims.get("cables")
    if c is None or isinstance(c, str):
        return {"placed": False, "note": c or "No cables in the geometry file."}
    if not isinstance(c, dict):
        fail(f"{src}: 'cables' must be a string or an object, not {type(c).__name__}")
    runs = c.get("runs")
    flags = c.get("power_flags", [])
    if not isinstance(runs, list) or not isinstance(flags, list):
        fail(f"{src}: 'cables' needs a 'runs' list, and 'power_flags' (if present) must be a list")
    out_runs = []
    for i, r in enumerate(runs):
        for k in ("id", "label", "kind", "points"):
            if k not in r:
                fail(f"{src}: cables.runs[{i}] needs '{k}'")
        if r["kind"] not in CABLE_KINDS:
            fail(f"{src}: cables.runs[{i}] ({r['id']}): kind '{r['kind']}' is not one of {', '.join(CABLE_KINDS)}")
        if not isinstance(r["points"], list) or len(r["points"]) < 2:
            fail(f"{src}: cables.runs[{i}] ({r['id']}): 'points' needs at least two [x, z] pairs")
        out_runs.append({"id": str(r["id"]), "label": str(r["label"]), "kind": r["kind"],
                         "points": pts(r["points"], f"cables.runs[{i}].points")})
    out_flags = []
    for i, f in enumerate(flags):
        for k in ("node", "circuit", "load_percent", "x", "z"):
            if k not in f:
                fail(f"{src}: cables.power_flags[{i}] needs '{k}'")
        out_flags.append({"node": str(f["node"]), "circuit": str(f["circuit"]), "load_percent": f["load_percent"],
                          "x": r3(f["x"]), "z": r3(f["z"])})
    return {"placed": True, "about": c.get("_about", ""), "confidence": c.get("confidence", ""),
            "runs": out_runs, "power_flags": out_flags}


# ---------------------------------------------------------------- layout
def holes(lay, src):
    if not isinstance(lay.get("holes"), list) or not lay["holes"]:
        fail(f"{src}: needs a non-empty 'holes' list")
    fps = lay.get("footprints", {})
    out = []
    for i, h in enumerate(lay["holes"]):
        for k in HOLE_NEEDS:
            if k not in h:
                fail(f"{src}: holes[{i}] ({h.get('name', '?')}) needs '{k}'")
        o = {k: v for k, v in h.items() if isinstance(v, (str, int, float, bool)) or v is None}
        o["c"] = pair(h["c"], f"holes[{i}].c")
        o["district"] = h.get("district") or DISTRICT_NAMES.get(h["d"], str(h["d"]))
        hh = {"c": o["c"], "th": h["th"]}
        L, W = h["L"], h["W"]
        o["deck"] = pts([l2w(hh, u, v) for u, v in ((-L / 2, -W / 2), (L / 2, -W / 2), (L / 2, W / 2), (-L / 2, W / 2))])
        o["tee"] = pts([l2w(hh, -L / 2 + 0.3, 0.0)])[0]
        beside = []
        for P in fps.get(str(h["n"]), []):
            P = pts(P, f"footprints[{h['n']}]")
            if same_poly(P, o["deck"]):
                continue
            xs, zs = [q[0] for q in P], [q[1] for q in P]
            small = max(xs) - min(xs) <= 0.5 and max(zs) - min(zs) <= 0.5
            beside.append({"kind": "totem" if small else "prop", "poly": P})
        o["beside"] = beside
        out.append(o)
    ns = [h["n"] for h in out]
    if len(set(ns)) != len(ns):
        fail(f"{src}: hole numbers repeat: {sorted(ns)}")
    return sorted(out, key=lambda h: -h["n"])


def same_poly(P, Q, tol=0.02):
    if len(P) != len(Q):
        return False
    return all(any(abs(p[0] - q[0]) < tol and abs(p[1] - q[1]) < tol for q in Q) for p in P)


def layout_name(about):
    m = re.match(r"\s*(Layout v[\w.]+(?:\s*\([^)]*\))?)", about or "")
    return m.group(1) if m else "The current layout"


def hubs(lay, src):
    h = lay.get("hubs", lay.get("hub"))
    if h is None:
        print(f"make_status_page: warning: {src} has no 'hub'; the map shows none", file=sys.stderr)
        return []
    if isinstance(h, list) and len(h) == 4 and all(isinstance(v, (int, float)) for v in h):
        h = [h]
    out = []
    for i, r in enumerate(h):
        if isinstance(r, dict):
            r = r.get("rect")
        if not (isinstance(r, list) and len(r) == 4):
            fail(f"{src}: hub {i} must be [x0, z0, x1, z1]")
        out.append([r3(v) for v in r])
    return out


def build(lay, dims, lsrc, dsrc):
    about = lay.get("_about", "")
    routes = lay.get("routes", {})
    if not isinstance(routes, dict):
        fail(f"{lsrc}: 'routes' must map a district letter to a list of hops")
    return {
        "source": {
            "layout_name": layout_name(about),
            "layout_about": about,
            "layout_file": os.path.relpath(lsrc, ROOT),
            "geometry": f"Geometry v{dims.get('version')} ({dims.get('date')})",
            "geometry_file": os.path.relpath(dsrc, ROOT),
        },
        "geo": geometry(dims, dsrc),
        "layout": {
            "hubs": hubs(lay, lsrc),
            "apron_x": lay.get("apron_x"),
            "routes": {k: [pts(hop, f"routes.{k}") for hop in v] for k, v in routes.items()},
            "sightline": pts(lay.get("sightline", []), "sightline"),
            "checks": lay.get("checks_m", {}),
        },
        "holes": holes(lay, lsrc),
        "cables": cables(dims, dsrc),
    }


def inject(path, data):
    page = open(path, encoding="utf-8").read()
    js = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    js = js.replace("</", "<\\/").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    block = BEGIN + "\nconst STATUS = " + js + ";\n" + END
    new, n = re.subn(r"/\* STATUS:BEGIN.*?/\* STATUS:END \*/", lambda m: block, page, flags=re.S)
    if n != 1:
        fail(f"{path}: STATUS markers found {n} times, expected exactly once")
    if new != page:
        open(path, "w", encoding="utf-8").write(new)
        print(f"injected status data into {os.path.relpath(path, ROOT)}")
    else:
        print(f"{os.path.relpath(path, ROOT)} already up to date")


def main():
    ap = argparse.ArgumentParser(description="Inject floor-plan data into the status page.")
    ap.add_argument("layout", nargs="?", default=DEFAULT_LAYOUT, help="layout JSON (default: floorplan/layout-v3-nyc.json)")
    ap.add_argument("dims", nargs="?", default=DEFAULT_DIMS, help="room geometry JSON (default: floorplan/auditorium-dimensions.json)")
    ap.add_argument("--page", default=DEFAULT_PAGE, help="status page to write into")
    ap.add_argument("--check", action="store_true", help="build and summarise the data without writing the page")
    a = ap.parse_args()
    lsrc, dsrc = os.path.abspath(a.layout), os.path.abspath(a.dims)
    lay = json.load(open(lsrc, encoding="utf-8"))
    dims = json.load(open(dsrc, encoding="utf-8"))
    data = build(lay, dims, lsrc, dsrc)
    g, cab = data["geo"], data["cables"]
    print(f"{data['source']['layout_name']}: {len(data['holes'])} holes, {len(data['layout']['hubs'])} hub(s), "
          f"{sum(len(v) for v in data['layout']['routes'].values())} route hops")
    print(f"{data['source']['geometry']}: room {g['room']['L']} x {g['room']['W']} m, "
          f"{len(g['doors'])} doors, {len(g['extras'])} other items")
    if cab["placed"]:
        print(f"cables: {len(cab['runs'])} runs, {len(cab['power_flags'])} power flags")
    else:
        print("cables: not placed yet (the page shows a note)")
    if not a.check:
        inject(a.page, data)


if __name__ == "__main__":
    main()
