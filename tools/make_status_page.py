#!/usr/bin/env python3
"""Inject the floor-plan data into the status page, so its map is drawn from the repo's files.

Usage:
    python3 tools/make_status_page.py [--layout floorplan/layout-v3-nyc.json]
                                      [--dims floorplan/auditorium-dimensions.json]
                                      [--page status/countdown-golf-status.html] [--check]

Reads the layout (hole positions, footprints, walk routes, hub, sightline and clearance checks,
written by tools/make_layout_nyc.py) and the room geometry (written by hand, every value labelled
measured, derived or not measured). Writes one JSON block into the page between the
/* STATUS:BEGIN */ and /* STATUS:END */ markers. The page's own script draws the map from it.
Edit this script or the source files, never the block. --check builds the block and prints the
summary without writing the page.

Re-run it whenever the layout or the geometry changes:
    python3 tools/make_layout_nyc.py floorplan/auditorium-dimensions.json floorplan --png
    python3 tools/make_status_page.py

Cables: `cables` in the geometry file is either a string (not placed on this geometry yet) or an
object {"_about", "confidence", "runs": [{"id", "label", "kind": "run"|"trunk"|"drop",
"points": [[x, z], ...]}], "power_flags": [{"node", "circuit", "load_percent", "x", "z"}]}.
For an object the page draws the runs as dashed lines labelled approximate and marks the power
flags; for a string it shows a short note that the cables aren't placed yet. Anything else fails.

Uses the standard library only.
"""
import argparse
import json
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DISTRICTS = {"A": "Downtown", "B": "Midtown"}          # names from docs/10-new-york-concept.md
CABLE_KINDS = ("run", "trunk", "drop")
BEGIN = "/* STATUS:BEGIN (generated by tools/make_status_page.py; edit the script, not this block) */"
END = "/* STATUS:END */"


def measured(conf):
    """True when the geometry file says a value was measured, or derived from measured values."""
    c = (conf or "").strip().lower()
    return c.startswith("measured") or c.startswith("derived")


def r3(v):
    return round(float(v), 3)


def pts(seq):
    return [[r3(x), r3(z)] for x, z in seq]


def l2w(h, u, v):
    t = math.radians(h["th"])
    return (h["c"][0] + u * math.cos(t) - v * math.sin(t), h["c"][1] + u * math.sin(t) + v * math.cos(t))


def fail(msg):
    sys.exit(f"make_status_page: {msg}")


def geometry(dims):
    room = dims["auditorium"]
    stage = dims["stage"]
    rw = dims["runway"]
    tip = rw["x"][1]
    out = {
        "version": dims.get("version"),
        "date": dims.get("date"),
        "room": {
            "L": room["length_x"], "W": room["width_z"],
            "L_measured": measured(room.get("length_confidence")),
            "W_measured": measured(room.get("width_confidence")),
        },
        "stage": {
            "front_x": stage["front_x"],
            "measured": measured(stage.get("front_x_confidence")),
            "curves": [
                {"wall_z": c["wall_z"], "along": c["along_front"], "out": c["out_from_front"],
                 "measured": measured(c.get("confidence"))}
                for c in stage.get("corner_curves", [])
            ],
        },
        "runway": {
            "x": rw["x"], "z": rw["z"], "length": rw["length"], "width": rw["width"],
            "measured": measured(rw.get("length_confidence")) and measured(rw.get("width_confidence")),
        },
        "golf_limit": {
            "x": dims["golf_limit"]["x"],
            "from_stage_front": dims["golf_limit"]["from_stage_front"],
            "past_tip": dims["golf_limit"]["past_runway_tip"],
            "measured": measured(dims["golf_limit"].get("from_stage_front_confidence")),
        },
        "zones": [{"id": z["id"], "label": z["label"], "x": z["x"], "z": z["z"]} for z in dims.get("zones", [])],
        "side_items": [],
        "doors": [],
    }
    sides = dims.get("runway_side_items", {})
    for side in sides.get("sides", []):
        for it in sides.get("items", []):
            a, b = it["from_tip"]
            o = it["out"]
            z = [rw["z"][0] - o, rw["z"][0]] if side == "top" else [rw["z"][1], rw["z"][1] + o]
            out["side_items"].append({
                "type": it["type"], "side": side, "x": [r3(tip - b), r3(tip - a)], "z": [r3(z[0]), r3(z[1])],
                "measured": measured(it.get("position_confidence")),
            })
    if "lf_platform" in dims:
        lf = dims["lf_platform"]
        out["lf_platform"] = {"label": lf.get("label", "LF platform"), "x": lf["x"], "z": lf["z"],
                              "measured": measured(lf.get("x_confidence")) and measured(lf.get("z_confidence"))}
    if "sound_console" in dims:
        sc = dims["sound_console"]
        out["console"] = {"x": sc["x"], "z": sc["z"], "measured": measured(sc.get("confidence"))}
    for d in dims.get("doors", []):
        if d.get("wall") == "back wall":
            out["doors"].append({"id": d["id"], "x": room["length_x"], "z": d["z"], "measured": measured(d.get("confidence"))})
    m = {k["id"]: k for k in dims.get("measurements", [])}
    out["measurements"] = {k: {"value": v["value"], "measured": measured(v.get("confidence"))} for k, v in m.items()}
    out["not_measured"] = dims.get("not_measured", [])
    return out


def cables(dims):
    c = dims.get("cables")
    if isinstance(c, str) or c is None:
        return {"placed": False, "note": c or "Not in this geometry file yet."}
    if not isinstance(c, dict):
        fail(f"'cables' must be a string or an object, not {type(c).__name__}")
    runs = c.get("runs")
    flags = c.get("power_flags", [])
    if not isinstance(runs, list) or not isinstance(flags, list):
        fail("'cables' object needs a 'runs' list (and 'power_flags', if present, must be a list)")
    out_runs = []
    for i, r in enumerate(runs):
        for k in ("id", "label", "kind", "points"):
            if k not in r:
                fail(f"cables.runs[{i}] has no '{k}'")
        if r["kind"] not in CABLE_KINDS:
            fail(f"cables.runs[{i}] ({r['id']}): kind '{r['kind']}' is not one of {', '.join(CABLE_KINDS)}")
        p = r["points"]
        if not isinstance(p, list) or len(p) < 2 or not all(isinstance(q, (list, tuple)) and len(q) == 2 for q in p):
            fail(f"cables.runs[{i}] ({r['id']}): 'points' must be a list of at least two [x, z] pairs")
        out_runs.append({"id": str(r["id"]), "label": str(r["label"]), "kind": r["kind"], "points": pts(p)})
    out_flags = []
    for i, f in enumerate(flags):
        for k in ("node", "circuit", "load_percent", "x", "z"):
            if k not in f:
                fail(f"cables.power_flags[{i}] has no '{k}'")
        out_flags.append({"node": str(f["node"]), "circuit": str(f["circuit"]), "load_percent": f["load_percent"],
                          "x": r3(f["x"]), "z": r3(f["z"])})
    return {"placed": True, "about": c.get("_about", ""), "confidence": c.get("confidence", ""),
            "runs": out_runs, "power_flags": out_flags}


def holes(lay):
    fps = lay.get("footprints", {})
    out = []
    for h in lay["holes"]:
        f = fps.get(str(h["n"]))
        if not f:
            fail(f"layout has no footprints for hole {h['n']}")
        out.append({
            "n": h["n"], "d": h["d"], "district": DISTRICTS.get(h["d"], h["d"]),
            "name": h["name"], "sign": h["sign"], "cls": h["cls"], "par": h["par"],
            "L": h["L"], "W": h["W"], "c": pts([h["c"]])[0], "th": h["th"], "glow": h["glow"],
            "surface": h.get("surface", ""), "play": h.get("play", ""), "prop": h.get("prop", ""),
            "clock": h.get("clock", ""),
            "tee": pts([l2w(h, -h["L"] / 2 + 0.3, 0.0)])[0],
            "deck": pts(f[0]),
            "totem": pts(f[1]) if len(f) > 1 else None,
            "props": [pts(p) for p in f[2:]],
        })
    return sorted(out, key=lambda h: -h["n"])


def build(lay, dims):
    if len(lay.get("holes", [])) != 10:
        print(f"make_status_page: warning: the layout has {len(lay.get('holes', []))} holes, not 10", file=sys.stderr)
    return {
        "source": {
            "layout": lay.get("_about", ""),
            "geometry": f"Geometry v{dims.get('version')} ({dims.get('date')})",
        },
        "geo": geometry(dims),
        "layout": {
            "hub": lay["hub"],
            "apron_x": lay.get("apron_x"),
            "routes": {k: [pts(hop) for hop in v] for k, v in lay.get("routes", {}).items()},
            "sightline": pts(lay.get("sightline", [])),
            "checks": lay.get("checks_m", {}),
        },
        "districts": DISTRICTS,
        "holes": holes(lay),
        "cables": cables(dims),
    }


def inject(path, data):
    page = open(path, encoding="utf-8").read()
    js = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    js = js.replace("</", "<\\/").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    block = BEGIN + "\nconst STATUS = " + js + ";\n" + END
    new, n = re.subn(r"/\* STATUS:BEGIN.*?/\* STATUS:END \*/", lambda m: block, page, flags=re.S)
    if n != 1:
        fail(f"{path}: STATUS markers found {n} times, expected exactly once")
    if new != page:
        open(path, "w", encoding="utf-8").write(new)
        print(f"injected status data into {path}")
    else:
        print(f"{path} already up to date")


def main():
    ap = argparse.ArgumentParser(description="Inject floor-plan data into the status page.")
    ap.add_argument("--layout", default=os.path.join(ROOT, "floorplan", "layout-v3-nyc.json"))
    ap.add_argument("--dims", default=os.path.join(ROOT, "floorplan", "auditorium-dimensions.json"))
    ap.add_argument("--page", default=os.path.join(ROOT, "status", "countdown-golf-status.html"))
    ap.add_argument("--check", action="store_true", help="build and summarise the data without writing the page")
    a = ap.parse_args()
    lay = json.load(open(a.layout, encoding="utf-8"))
    dims = json.load(open(a.dims, encoding="utf-8"))
    data = build(lay, dims)
    cab = data["cables"]
    print(f"{len(data['holes'])} holes, hub {data['layout']['hub']}, geometry v{dims.get('version')}")
    if cab["placed"]:
        print(f"cables: {len(cab['runs'])} runs, {len(cab['power_flags'])} power flags")
    else:
        print("cables: not placed yet (the page shows a note)")
    if not a.check:
        inject(a.page, data)


if __name__ == "__main__":
    main()
